<h1 class="title">LEGGERE</h1>

<p class="text">Si legge per svariati motivi: per studiare, per cercare informazioni, per formarsi delle opinioni, per raggiungere degli obiettivi, per il piacere di immaginare e di identificarsi nei personaggi. Il modo di leggere cambia secondo i tipi di testo e le ragioni per cui si legge. In generale, diciamo che la lettura ha successo quando si comprende il contenuto del testo: ciò che accade, i collegamenti fra le diverse informazioni, i ragionamenti che vengono proposti, le intenzioni di chi scrive, la validità e l’interesse di ciò che si legge. Come per lo sport, che più lo si pratica e ci si allena più si diventa bravi, così avviene anche per la lettura: più testi di diverso tipo si leggono più si diventa lettori esperti. 
</p>

<h2 class="section-title">Interpretare i risultati</h2>

<p class="text">
	La tabella di autovalutazione ti presenta le diverse abilità che vengono attivate quando si legge e il punteggio complessivo ti segnala il probabile livello al quale ti trovi ora, livello che però conviene verificare con le applicazioni proposte.
</p>

