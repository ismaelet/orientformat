<h1 class="title">STILI ATTRIBUTIVI<br>E TEORIE DEL SÉ</h1>

<p class="text">A volte abbiamo successo, a volte non raggiungiamo i nostri obiettivi. Se è andata male, spesso cerchiamo il colpevole: gli altri che ce l’hanno con noi, la sfortuna, la nostra incapacità… Se è andata bene, più spesso tendiamo a pensare che siamo bravi e che abbiamo avuto quello che ci meritiamo. Il modo in cui assegniamo meriti e colpe riguarda proprio lo stile attributivo, che non è uguale tra le persone.<br>
   L’idea generale che abbiamo sull’intelligenza influisce molto sullo stile attributivo. Due sono le “teorie” basilari sulla propria intelligenza:<span class="break"></span>
<strong>a)</strong> c’è chi pensa che intelligenti si nasce<span class="break"></span>
<strong>b)</strong> c’è chi pensa che intelligenti si diventa pian piano con le conoscenze e le esperienze.<span class="break"></span>
Ovviamente nel primo caso si è poco portati a cambiare, sia che ci si pensi brillanti o incapaci; nel secondo caso si è più disponibili a provare strade diverse.
</p>

<h2 class="section-title">Interpretare i risultati</h2>

<p class="text">Nel grafico compaiono gli otto stili attributivi più frequenti. Posizionandoti col mouse su ogni stile, compare una breve descrizione. Se, ripetendo più volte la tua valutazione a distanza di tempo, uno stile prevale sugli altri, significa che in questo periodo quello è lo stile attributivo che ti caratterizza di più. Potresti chiederti, discutendone anche con qualcuno, se quello stile è il più favorevole per la tua crescita personale.
</p>

