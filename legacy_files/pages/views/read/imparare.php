<h1 class="title">Imparare</h1>

<h1 class="section-title">Imparare come si impara</h1>
<p class="text">La <a href="#g-competenza" class="link">competenza</a> forse più importante, nel mondo complesso e mutevole in cui viviamo,
	è imparare come si impara. Ciò significa possedere un <a href="#g-metodo" class="link">metodo</a> flessibile non solo
	per acquisire conoscenze, ma anche per riflettere sul modo stesso di organizzare il
	proprio lavoro, di pensare e ragionare.<br>
	Il significato non si travasa semplicemente dal testo alla mente di chi studia, ma è
	un oggetto dinamico e processuale che deve essere ricostruito dal lettore.
	Operazione che ha qualche probabilità di riuscita solo con un <a href="#g-atteggiamento" class="link">atteggiamento</a> attivo
	e critico. È molto utile a tale scopo poter disporre di domande con le quali
	sollecitare le risposte da parte del testo. Si comprende quando si sa che cosa
	cercare. Naturalmente non è detto che il testo risponda sempre a tutte le
	domande. Tuttavia ciò che è importante è la stessa competenza interrogante, che
	deve far parte del corredo dello studente efficace.<br>
	A volte però non basta. Anche il semplice rendersi conto di capire o non capire, e
	modificare di conseguenza il comportamento di lettura, non è affatto un dato
	scontato, ma un’abilità di straordinaria importanza. I cattivi lettori, che si
	arrestano a livelli di comprensione molto superficiali, sembrano infatti non rendersi
	conto di non capire, ignorando eventuali incongruenze del testo. Alla base dei loro
	problemi di comprensione sembra esservi un comune deficit che definiremo
	“<a href="#g-metacognizione" class="link">metacognitivo</a>”, in quanto ciò che fa difetto è la consapevolezza da parte del
	lettore sul proprio modo di operare. In particolare, i cattivi lettori non sono in
	grado di utilizzare <a href="#g-strategia" class="link">strategie</a> <a href="#g-autoregolazione" class="link">autoregolative</a> efficaci in caso di mancata
	comprensione. Le strategie di cui il lettore può disporre sono un aspetto essenziale
	della metacomprensione. Proviamo ad approfondire un po’ la questione.</p>

<h1 class="section-title">Le strategie</h1>
<p class="text">Le strategie nascono come risposta ai limiti dell’uomo nell’affrontare compiti, in
	particolare quelli nuovi e complessi. Come la bussola, che è uno strumento noto per
	affrontare la navigazione in mari ignoti, dove non si può navigare a vista, così le
	strategie sono strumenti elaborati in contesti familiari per fare fronte a situazioni
	nuove.<br>
	Una grandissima attenzione alle strategie come strumenti al servizio del
	“processore umano di informazioni” nacque tra il 1953 e il 1956, quando si
	realizzarono diverse ricerche che diedero l’avvio alla grande avventura cognitivista,
	che dura tuttora. Fu in questo contesto che fu avanzata l’ipotesi di un filtro
	attenzionale che avrebbe il compito di bloccare informazioni indesiderate, lasciando
	entrare solo quelle che meritano un’analisi ulteriore, e ciò per la semplice ragione
	che la nostra <a href="#g-memoria" class="link">memoria</a> di lavoro ha una capacità limitata. La mente umana riesce a
	temperare questa debolezza strutturale, congenita, nel raggiungere i suoi obiettivi
	e risolvere i suoi <a href="#g-problema" class="link">problemi</a>, facendo ricorso a sequenze di atti che nello stesso 1956
	verranno chiamate appunto “strategie”. L’interazione più o meno efficace dell’uomo
	col mondo dipende dalle strategie in suo possesso.<br>
	Quando una strategia viene applicata ripetutamente si automatizza, per cui non è
	più necessario richiamarla alla mente consapevolmente. Il problema è acquisirla, e
	proprio quella giusta per il problema posto in situazioni date. Nella grandissima
	parte dei casi l’acquisizione avviene spontaneamente, però qualche volta ciò non
	avviene, oppure si possono acquisire e interiorizzare strategie sbagliate. In questi
	casi la mediazione di qualcuno, ad esempio un insegnante, per acquisire una
	strategia nuova o per modificare una strategia sbagliata, diviene essenziale.<br>
	Prima ancora che su un apprendimento esplicito, i comportamenti di studio di un
	alunno, le sue strategie, vengono acquisite spontaneamente e inconsapevolmente
	attraverso imitazione. Consolidandosi con l’abitudine, divengono “<a href="#g-teoria" class="link">teorie ingenue</a>”,
	alimentate da convinzioni, da pregiudizi, da stereotipi, che possono favorire oppure
	ostacolare la comprensione e l’apprendimento di strategie consapevoli ed efficaci.
	Per questo assume un’importanza decisiva l’acquisizione di metodologie consapevoli e
	controllate da parte di insegnanti esperti, che stimoleranno nello studente
	strategie consapevoli, snelle e poco impositive. Perché esse risultino veramente
	efficaci, devono però essere soddisfatte almeno tre condizioni:<br><br>
	- le strategie e le procedure corrette devono essere ripetute più volte fino ad
	essere interiorizzate, operando poi così in modo automatico;<br>
	- lo studente deve essere <a href="#g-motivazione" class="link">motivato</a> a sostituire eventuali cattive abitudini con
	strategie più corrette ed efficaci;<br>
	- un metodo di studio non può essere trasmesso in modo meccanico, ma deve essere
	lo studente ad impadronirsene gradualmente, adattandolo flessibilmente al proprio
	<a href="#g-stile" class="link">stile</a> cognitivo (> Profilo personale > Stili cognitivi), ai diversi problemi e ai singoli
	contesti.
</p>

<h1 class="section-title">Metacognizione e studio strategico</h1>
<p class="text">Compiti diversi richiedono strategie diverse. Però ci sono anche caratteristiche
	comuni alle varie strategie, che caratterizzano l’operare strategico in quanto tale.
	Ogni strategia, se è flessibile, richiederà di anticipare in corso d’opera gli esiti
	finali. Se questi non sono soddisfacenti, occorrerà modificare o sostituire la
	strategia in atto. Possiamo raffigurare nel modo seguente questo processo
	autoregolativo (Figura 1).<br><br>

	Figura 1 - Il processo autoregolativo

	<img src="<?= client_path('img1.png') ?>" alt="" class="block mar-v-2 mwid800 wid-100">

	Nei compiti esecutivi, di tipo familiare e legati al saper fare, la scelta di strategie
	alternative avviene nell’ambito di un repertorio collaudato e ciò si realizza in modo
	relativamente automatico, soprattutto se i compiti sono semplici. I compiti nuovi
	invece, legati all’agire, soprattutto se sono complessi e richiedono iniziativa e
	inventiva, esigono un diverso tipo di controllo, che si definisce metacognitivo: è
	l’agire stesso che diviene campo d’indagine, dovendo essere <a href="#g-automonitoraggio" class="link">monitorato</a> e valutato
	nel corso del suo svolgimento. Nell’<a href="#g-autoregolazione" class="link">autoregolazione</a> metacognitiva entrano
	continuamente in gioco tre operazioni: monitoraggio dell’esecuzione in corso,
	valutazione e regolazione. In questi aggiustamenti continui intervengono in modo
	rilevante fattori non cognitivi in senso stretto quali la motivazione, il senso di
	autoefficacia, la percezione di <a href="#g-emozione" class="link">stati emotivi</a> come l’ansia o la noia e, più in generale,
	quelle che sono state definite “capacità di autoregolazione fine”, che si esplicano
	nel fatto di accorgersi per tempo che si sta entrando in una situazione di difficoltà,
	di reagire a ciò, di identificare le fonti di disagio, di eliminarle, di prevenire
	problemi simili in futuro.<br>
	Insomma, in un comportamento strategico si intrecciano sinergicamente la
	conoscenza della strategia, l’abilità nell’applicarla e il controllo consapevole,
	trasformando la strategia se occorre. Tutto questo a volte non basta, se non è
	supportato da competenze culturali e conoscenze contestuali, cioè da quelle
	"conoscenze silenziose" che permettono di distinguere ciò che è rilevante (le
	famose "parole-chiave") da ciò che non lo è.
</p>

<h1 class="section-title">Comprendere con metodo</h1>
<p class="text">La finalità consiste quindi nell’acquisire strategie di lettura atte a fronteggiare
	testi che possono comportare difficoltà interpretative. Lettura strategica che si
	intreccia con altre competenze (scrittura, attenzione, memoria, riassunto ecc.) (>
	Competenze di base), che concorrono a formare quella complessa super-competenza
	che si chiama “metodo di studio”.<br>
	Il “metodo”, in generale, è un procedimento razionale e ripetibile finalizzato
	all’acquisizione di una conoscenza o alla soluzione di un problema (o di una classe di
	problemi). In quanto ripetibile, è anche comunicabile e quindi socializzabile; in
	quanto razionale, si deve configurare come prescrittivo, economico (per quanto
	possibile), completo ed esplicito.<br>
	Il metodo da solo però non è detto che basti. Infatti la stessa parola “studio”,
	che deriva da studēre (“applicarsi, dedicarsi con zelo”), implica che ci sia anche
	investimento cognitivo, impegno. L’efficacia o inefficacia nello studio si manifesta
	nei risultati delle prestazioni del soggetto. Sono questi dati verificabili che
	consentono di risalire in modo indiziario alle procedure e ai metodi impiegati, che
	siano essi consapevoli o inconsapevoli.<br>
	Le prime ricerche sul metodo di studio risalgono agli anni Venti ed erano rivolte a
	soggetti che presentavano difficoltà di apprendimento. Si notò da subito la
	difficoltà nel mantenere e nel trasferire i metodi appresi, perché non si tenevano
	nel dovuto conto le variabili psicologiche di mediazione (<a href="#g-attributivo" class="link">stile attributivo</a>, <a href="#g-autostima" class="link">autostima</a>, autoefficacia, <a href="#g-autorappresentazione" class="link">autorappresentazione</a>) e la necessità di un approccio flessibile, dovuto ai diversi stili cognitivi dei lettori e alle variabili contestuali non del tutto
	prevedibili.<br>
	Nell’accezione in cui lo intendiamo oggi, il “metodo di studio” nacque nel secondo
	dopoguerra e si rivolgeva soprattutto a studenti universitari. Si occupava
	prioritariamente della comprensione dei testi, attraverso lettura veloce e stesura
	di appunti. Successivamente queste tecniche verranno estese ad una gamma molto
	più ampia di fruitori, includendo anche regole pratiche per “fare ricerca” (così come
	la si intende nella scuola). In tempi più recenti, la riflessione teorica e le proposte
	di tipo operativo e procedurale hanno coperto altri settori di importanza nevralgica,
	quali l’attenzione, la memoria, la scrittura, la motivazione, l’autoregolazione emotiva
	ecc. Ciò in considerazione del fatto che i vari aspetti (ad esempio cognitivi ed
	emozionali) non si possono separare nettamente senza compromettere l’efficacia
	complessiva. Naturalmente, questa dilatazione del quadro di riferimento ha
	complicato notevolmente le cose.</p>

<h1 class="section-title">Le sette fasi del metodo</h1>
<p class="text">Negli Stati Uniti in particolare si è investito molto in questo settore, ma i risultati
	sono stati spesso deludenti. Il momento critico c'è quando le procedure apprese in
	un corso specifico sul metodo di studio si devono trasferire nel lavorare quotidiano,
	in classe e a casa. Spesso riaffiorano e prendono il sopravvento le teorie ingenue
	precedentemente e spesso inconsapevolmente acquisite. Le maggiori probabilità di
	successo si hanno quando il lettore riesce a trovare il suo metodo e adattarlo
	flessibilmente alle mutevoli esigenze.<br>
	Tuttavia, quando non si legge per divertirsi, ma per impadronirsi di un testo, è
	possibile percorrere alcune fasi che si sono rivelate generalmente efficaci (Figura
	2).<br><br>
	Figura 2 - Il metodo di lettura

	<img src="<?= client_path('img2.png') ?>" alt="" class="block mar-v-2 mwid800 wid-100">

	In ciascuna fase si vogliono raggiungere obiettivi diversi, ma tutti rivolti
	all’obiettivo fondamentale di appropriarsi del contenuto del testo. Nella fase (1) di

	pre-lettura ci si interroga : quali scopi voglio raggiungere leggendo il testo? Quali
	ricordi mi suggerisce il titolo o il nome dell’autore? Questa fase serve per stimolare
	delle aspettative, che favoriranno il dialogo col testo. Può anche essere condotta
	dall’insegnante (brainstorming della classe). Nella fase (2), la lettura orientativa
	serve per scorrere rapidamente il testo con lo scopo di farsene un’idea globale, che
	potrà poi essere confermata o falsificata. La (3) lettura analitica è una lettura
	concentrata che smonta e ricompone continuamente il testo: procede di solito per
	blocchi di informazioni, le unità di lettura, che spesso presentano delle strutture
	riconoscibili. Quando ci si rende conto di trovarsi di fronte a punti importanti o
	difficili, la lettura rallenta, quando si incontrano invece dei punti più semplici o poco
	importanti la lettura si fa più veloce. Dopo ogni unità di lettura conviene fermarsi a
	(4) riflettere: si è capito tutto o conviene rileggere qualche punto oscuro? Quali
	sono le parole più importanti, la parole-chiave? Si sottolineano, ma in maniera
	molto parca, evidenziando solo gli elementi strutturali del testo. Centrale è il ruolo
	della frase guida, che indica il tipo di strutturazione dell’unità di lettura. Inoltre in
	questa fase si può dare un titolo (una parola-concetto) all’unità di lettura sulla quale
	ci si è soffermati. Prima di procedere, conviene (5) ripetere in poche parole, a testo
	coperto, il contenuto dell’unità: questo aiuta non solo a ricordare di più, ma anche a
	comprendere meglio la parte seguente del testo. Tutte queste operazioni vengono
	ripetute per ogni unità di lettura. Alla fine, per ricostruire lo schema del testo, ci si
	serve (6) di mappe o grafici, oppure, per i lettori che hanno uno stile marcatamente
	uditivo o visivo verbale, di riassunti scritti o orali, tutti strumenti che servono non
	solo a rielaborare il testo, comprendendolo più a fondo, ma anche a ricordarlo
	meglio. Infine (7) la revisione di tutto il percorso, che dovrebbe essere effettuata
	diverse volte a distanza di tempo, favorisce un ricordo più duraturo, addirittura
	permanente: quel testo è diventato parte del lettore, è uno strumento che si potrà
	riutilizzare per tutte le occasioni successive di apprendimento.<br>
	Non tutti i lettori esperti dedicano a queste sette fasi lo stesso impegno. In base
	agli stili personali e alle diverse esigenze, ci si soffermerà più su certe fasi o
	addirittura se ne trascureranno alcune. Nell’esempio proposto nel software ci siamo
	soffermati solo su tre fasi in particolare.
</p>

<h1 class="section-title">Saper riassumere</h1>
<p class="text">Si legge per comprendere e si comprende per ricordare. Se dopo pochi minuti si
	dimenticasse completamente ciò che si è letto, non avrebbe senso leggere. Ebbene,
	l’attività che non solo manifesta nel modo più chiaro se effettivamente c’è stata una
	comprensione approfondita, ma che favorisce un mantenimento dei concetti
	essenziali nella memoria a lungo termine, è proprio il riassunto.<br>
	Sapere riassumere bene significa praticare efficacemente quattro attività
	fondamentali:<br><br>
	<span class="fw-bold">- Selezionare</span><br>
	Si seleziona evidenziando. È importante sapere che questa attività non viene fatta
	una volta per tutte, ma è ricorsiva: si ritorna più volte sulle parole e sulle parti

	evidenziate con simboli diversi (penna rossa, evidenziatore usato di piatto ecc.), in
	base anche a quanto si ricorda oppure si è dimenticato.<br><br>
	<span class="fw-bold">- Ridurre e generalizzare</span><br>
	Sono due attività collegate: per poter ridurre il testo, si richiede, oltre che
	trascurare le informazioni inessenziali, anche di poterle generalizzare, ricorrendo a
	concetti sovraordinati e ad iperonimi (“fiore” è iperonimo di “margherita”, così come
	“partenza” è un concetto sovraordinato rispetto ad azioni più specifiche come
	“preparare i bagagli”, “prenotare l’albergo”, “fare il biglietto” ecc.) . Anche l’uso di
	brevi titoli o “parole-concetto” di fianco alle unità di lettura già selezionate è
	un’attività molto utile che evidenzia la capacità di generalizzare.<br><br>
	<span class="fw-bold">- Ricostruire</span><br>
	Il vero nodo della questione è però la quarta abilità, cioè la costruzione di un
	riassunto che restituisca al destinatario la struttura semantica del testo di
	partenza, svincolandosi dall’ordine di esposizione. Un modo per fare centro
	sull’obiettivo (la struttura compositiva) consiste nel descrivere discorsivamente la
	mappa concettuale del testo.
</p>

<h1 class="section-title">Comprendere il testo espositivo</h1>
<p class="text">Le difficoltà straordinarie insite nell’apprendimento della lettura e della scrittura
	hanno costituito per secoli vere e proprie barriere fra il bambino e l’adulto e anche
	fra il bambino e l’adolescente, cadenzando i passaggi da un’età all’altra. La
	complessità che queste competenze comportano richiede molto tempo, investimenti
	cognitivi notevoli e non ammette troppe accelerazioni<sup>1</sup>.<br>
	I testi espositivi, accessibili al <a href="<?= client_url('/read?id=13#comprendere') ?>" class="link">pensiero paradigmatico</a>, sono centrati sul
	contenuto del messaggio, anche se contengono spesso delle tesi sulle quali si vuole
	ottenere il consenso del destinatario, ibridandosi così col <a href="<?= client_url('/read?id=13#tipologie') ?>" class="link">tipo di testo</a> che si
	definisce argomentativo. Che cosa fa un lettore esperto quando comprende un
	testo?<br>
	Potremmo dire che un lettore riesce a sbrogliare la matassa testuale se riesce a
	districare le tre reti che la costituiscono, relative a tre macro-abilità coinvolte:<br><br>
	1. la focalizzazione, che mette in evidenza la RETE TEMATICA,<br>
	2. la spiegazione, che coglie la RETE ESPLICATIVA<br>
	3. la valutazione che fa emergere la RETE ENUNCIATIVA del testo.<br><br>
	Proviamo a considerare queste abilità più in dettaglio.<br>
	Cogliendo la rete tematica riusciamo a identificare delle “figure”, cioè
	l’argomento di cui si parla, il topic (di chi? di che cosa?); ad attribuire ad esse delle
	caratteristiche il comment (che cosa si dice), e a collocarle su uno sfondo (dove?

	1 «Imparare a leggere significa imparare a rispettare le regole di una complessa tradizione logica e retorica che
	induce a considerare il valore delle frasi in un modo cauto e rigoroso e, ovviamente, a modificare continuamente i
	significati a mano a mano che si presentano nuovi elementi. La persona capace di leggere deve imparare ad essere
	riflessiva e analitica, paziente e sicura di sé, sempre pronta, dopo dovuta considerazione, a dire di no a un testo.
	Questo modo di comportarsi non è facile ad apprendersi da parte del giovane, e infatti va appreso per gradi. Per
	questo motivo ci si aspetta dal giovane lettore che all’inizio sappia solo parafrasare, non valutare; per questo stesso
	motivo non ci si aspetta che un bambino possa leggere» (Postman N., 1984, La scomparsa dell’infanzia, Roma,
	Armando Editore, pp. 99-100.)

	quando?). La risposta a queste domande fondamentali permette di acquisire una
	conoscenza di base del testo. La si ottiene con un tipo di lettura che chiameremo
	“globale”.<br>
	Individuando le informazioni relative alla seconda rete, quella esplicativa, il
	lettore riesce a “farsi una ragione” di quello che ha colto nella rete tematica:
	individua le cause, gli scopi (perché?), il modo di svolgimento (come?) e le
	conseguenze. Per cogliere questa rete si richiede solitamente una comprensione più
	approfondita, ottenibile solo con una lettura “analitica”. Alcune informazioni e
	collegamenti, che spesso non compaiono nel testo di superficie, sono infatti
	ricostruibili solo in modo inferenziale.<br>
	La rete che abbiamo definito “enunciativa” è quella relativa all’enunciatore o
	autore del testo, del quale si cercano le intenzioni, le forme di ragionamento con le
	quali vuole ottenere i suoi obiettivi e il grado di certezza in base al quale fornisce le
	informazioni (ne sono una spia modalizzatori come “forse”, “probabilmente”,
	“sembrerebbe” ecc.). Non solo: questa rete riguarda anche il destinatario del testo,
	il lettore stesso, che esprime valutazioni sul grado di attendibilità delle fonti e
	delle prove addotte a sostegno di una tesi o di un ragionamento. Chiameremo
	“critica” la lettura di questo tipo, che include anche la possibilità di una valutazione
	emotiva (impatto emotivo del testo sul lettore) e una valutazione estetica (mi piace
	o è valido per questi motivi, non convince per questi altri motivi).<br>
	Dal primo al terzo tipo di lettura la complessità aumenta progressivamente.</p>

