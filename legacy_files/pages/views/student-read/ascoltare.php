<h1 class="title">ASCOLTARE</h1>

<p class="text">Il primo obiettivo di chi ascolta è capire ciò che si dice. Si capisce solo se si riesce a seguire.  Come si fa? Se ciò che viene detto è semplice e interessa molto, seguire è facile e non richiede raccomandazioni particolari. Il problema nasce quando gli argomenti trattati sono più difficili, richiedono un ascolto prolungato e non accendono interessi particolarmente vivi. Ciò succede spesso, soprattutto a scuola, dove imparare ad ascoltare efficacemente è però particolarmente importante, perché è una delle vie principali per crescere umanamente e culturalmente. 
</p>

