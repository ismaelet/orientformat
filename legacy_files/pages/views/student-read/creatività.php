<h1 class="title">CREATIVITÀ E<br>AUTOIMPRENDITORIALITÀ</h1>

<p class="text">In qualunque contesto, le capacità di trovare soluzioni nuove, di essere propositivi, originali, autonomi, di avere iniziativa, in una parola essere creativi, sono doti apprezzabili, talvolta indispensabili. In ambito lavorativo, tutto questo si traduce in “auto-imprenditorialità”. Per capire e prevedere quanto in prospettiva si è portati ad essere imprenditori di sé stessi, occorre chiedersi ora quanto si è creativi, il che non significa essere necessariamente degli artisti o degli inventori geniali, ma semplicemente possedere in misura adeguata le qualità che caratterizzano la personalità e il pensiero creativi. 
</p>

<h2 class="section-title">Interpretare i risultati</h2>

<p class="text">
	Ciascun petalo del “fiore” che trovi nel riepilogo ti indica in quale percentuale pensi di possedere, almeno per ora, il tipo di pensiero o la particolare qualità che in genere caratterizzano un’elevata propensione alla creatività e all’autoimprenditorialità. 
</p>

