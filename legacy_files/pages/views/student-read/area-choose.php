<h1 class="title">SCEGLIERE</h1>

<p class="text">Gli interessi nascono dall’esposizione alle esperienze: ambienti nuovi, persone diverse, successi o
	sconfitte possono determinare nuovi interessi o spegnere interessi precedenti, soprattutto alla tua età
	caratterizzata da rapidi cambiamenti. In generale però è importante interrogarsi sui propri interessi, perché
	ci dà un’apertura sulla realtà e un orientamento sul futuro.
</p>

<h2 class="section-title">Interpretare i risultati</h2>

<p class="text">
	Tieni presente che gli interessi non coincidono necessariamente con le abilità. Ad esempio, potresti essere
	interessato/a a diventare un grande sciatore o una ballerina famosa, ma non disporre delle doti necessarie
	per raggiungere quelle mete.<br>
	Il profilo che risulta dal questionario può risultare molto differenziato fra le diverse aree. Ciò significa che
	hai già delle idee abbastanza chiare su ciò che ti interessa. Viceversa, potresti avere risultati molto simili,
	poco differenziati tra le diverse aree. Ciò può dipendere dal fatto che hai una grande molteplicità di
	interessi oppure, al contrario, che non hai ancora strutturato interessi articolati e solidi. E che è arrivato il
	momento di guardarsi attorno con più attenzione.
</p>

