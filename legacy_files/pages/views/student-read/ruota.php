<h1 class="title">LA RUOTA DELLE EMOZIONI</h1>

<p class="text">Si può essere intelligenti in tanti modi, non solo nel pensare, anche nel vivere le proprie emozioni. L’intelligenza emotiva si manifesta a diversi livelli: al livello più basso c’è la capacità di provare un’emozione, rendendosi conto di stare bene o di stare male. Ad un livello più alto si è capaci di riconoscere e nominare le emozioni che si provano e i pensieri ad esse legati. Un livello ancora più alto c’è quando si riesce a tenere sotto controllo emozioni negative come l’ansia, la collera e la tristezza. Su questa base si conquista il livello più alto, che è quello dell’empatia, ossia la capacità di mettersi nella situazione emotiva che l’altro sta vivendo.
</p>

<h2 class="section-title">Interpretare i risultati</h2>

<p class="text">
	Ci sono due indicatori che segnalano i progressi nel diventare più intelligenti emotivamente: il numero delle parole che si possiedono per nominare le emozioni e quanto spesso e facilmente si riconoscono in sé stessi e negli altri, anche nei personaggi dei film e dei romanzi.
</p>

