<h1 class="title">RICORDARE</h1>

<p class="text">L’attenzione, filtrando gli stimoli esterni e interni, crea il nostro mondo. Ma è la memoria che lo conserva, più a lungo e più precisamente quanto più stabili sono le tracce che si formano.
C’è un ricordare che si attiva spontaneamente e un ricordare che richiede una scelta e un impegno intenzionale. Alcuni ricordi si perdono, altri rimangono più a lungo, soprattutto se vengono utilizzati e ripetuti di più. Per questo è opportuno avere un metodo per ricordare le informazioni più importanti: chiedersi quale uso voglio fare delle informazioni, scegliendo quelle più importanti, richiamarle immediatamente e ripeterle in modo mirato.  
</p>

