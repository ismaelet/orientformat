<h1 class="title">STARE ATTENTI</h1>

<p class="text">Tutti noi siamo immersi in un’enorme quantità di stimoli, ma solo una piccolissima parte di questi attirano la nostra attenzione e vengono poi ricordati. L’attenzione è un filtro col quale entriamo in rapporto con la realtà, col quale costruiamo il nostro mondo. Ci sono attività che non richiedono un grande sforzo per stare attenti: quando conversiamo con amici, giochiamo, svolgiamo attività piacevoli. In questi casi l’attenzione scatta in automatico. Quando invece siamo esposti ad attività più impegnative, ad esempio seguire una spiegazione a lezione, dobbiamo esercitare un controllo volontario sulla nostra attenzione. Siccome è normale distrarsi, per avere un rendimento massimo dalla nostra attenzione è necessario imparare a scegliere tra cose importanti, che non vogliamo assolutamente perdere, e cose più trascurabili. 
</p>

<h2 class="section-title">Interpretare i risultati</h2>

<p class="text">
	La mappa che hai ottenuto realizzando il questionario ti indica i sei aspetti fondamentali per riuscire a regolare la tua attenzione. Il settore dove compare un punteggio basso (0/1) è quello nel quale dovresti impegnarti di più.
</p>

