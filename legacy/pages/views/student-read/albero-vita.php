<h1 class="title">L’ALBERO DELLA VITA</h1>

<p class="text">Questo strumento ti serve per fare il punto sul percorso che hai fatto finora e sulle tue aspettative future. Naturalmente si tratta solo di ipotesi, che potrai cambiare anche a distanza di poco tempo, magari dopo averne discusso con qualcuno di tua fiducia.
</p>

<h2 class="section-title">Interpretare i risultati</h2>

<p class="text">
	Naturalmente c’è una distanza fra te e la sagoma che hai scelto: la vita è molto più ricca e complessa di quello che un disegno può rappresentare. La scelta inoltre può dipendere da fattori che possono cambiare anche rapidamente: il particolare stato d’animo del momento, un fatto recente che ti è capitato, nuove persone che sono entrate nel tuo orizzonte o persone che hai perso di vista.
</p>

