<h1 class="title">LA RESILIENZA</h1>

<p class="text">Le situazioni difficili ci richiedono di reagire in qualche modo. Fin da piccoli, alcuni di noi sembrano più capaci e determinati, altri più insicuri e ansiosi. La capacità di reagire viene definita “resilienza”. Essere più resilienti rende la vita più semplice. È importante sapere che la resilienza può migliorare molto nel tempo. Questo accade se ragioniamo su quello che ci succede e cerchiamo modi personali di affrontare le difficoltà. 
</p>

<h2 class="section-title">Interpretare i risultati</h2>

<p class="text">
	La posizione che occupi nella scalata alla vetta è la media delle tue valutazioni. Dopo avere riflettuto sulle singole risposte, ed esserti eventualmente confrontato con qualcuno, potrai rifare il questionario.
</p>

