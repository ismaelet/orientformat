							<td>L'Esploratore basa la sua ricerca su articoli di blog o post sui social media che parlano di nuove
								tendenze del cyberbullismo.</td>
							<td>Il Critico chiederebbe:
								<em>“Queste ‘novità’ provengono da ricerche accademiche, da forze dell’ordine o da un influencer?
