			<li>
				<h4>Analisi Critica del Piano dello Stratega (esecuzione e conseguenze)</h4>
				<p>Lo Stratega propone un piano d’azione chiaro e suddiviso in compiti. Il Critico ha il compito di scovare i punti
					deboli nell’esecuzione e nelle previsioni di impatto.</p>

