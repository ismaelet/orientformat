						<tr>
							<td><strong>Cerco sempre i <strong>punti deboli</strong> di una spiegazione o di una proposta.</strong></td>
							<td>Lo Stratega stabilisce: “Entro 48 ore, parleremo con i genitori di tutti i soggetti coinvolti.”</td>
							<td>Il Critico domanderebbe:
								<em>“Qual è il punto debole di questo piano? Se i genitori del bullo non collaborano o minimizzano il
