									del servizio sociale scolastico) in caso di fallimento della prima mossa.”</em>
							</td>
						</tr>

						<tr>
							<td><strong>Mi interrogo spesso sulle <strong>reali intenzioni</strong> di chi parla.</strong></td>
							<td>Lo Stratega propone di coinvolgere un particolare insegnante o dirigente.</td>
							<td>Il Critico potrebbe riflettere:
								<em>“Al di là delle parole, l’insegnante Tizio vuole davvero risolvere il problema o vuole solo che la
