						<tr>
							<td><strong>Le soluzioni semplici e affrettate non mi convincono.</strong></td>
							<td>L'Esploratore potrebbe proporre di “denunciare immediatamente tutti i bulli online”.</td>
							<td>Il Critico obietterebbe che questa è una soluzione <strong>affrettata</strong>. Chiederebbe:
								<em>“Abbiamo considerato il rischio di ritorsione (il bullismo potrebbe intensificarsi offline)?
									Una denuncia è la soluzione più efficace per una vittima minorenne o un intervento educativo
