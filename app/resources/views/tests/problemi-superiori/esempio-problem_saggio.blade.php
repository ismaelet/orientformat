		<p class="text-block">Il ruolo del Saggio è agire come <strong>catalizzatore emotivo e mediatore
				decisionale</strong>,
			garantendo che il gruppo non si paralizzi a causa del conflitto tra la creatività (Esploratore/Stratega) e il
			realismo (Critico).<br>
			Dato che il Saggio si accorge subito se c'è qualcosa che non va nel gruppo e propone di discuterne, e può mettersi
			nei panni degli altri,
			il suo intervento sarebbe mirato a <strong>riconoscere il valore di ogni contributo</strong> e a
			<strong>ricostruire la coesione</strong> per finalizzare l'azione sul problema del cyberbullismo.
		</p>

		<ol>
			<li>
				<h4>Riconoscimento del Conflitto e Ascolto Empatico</h4>
				<p>Il Saggio non ignorerebbe la tensione, ma la porterebbe in superficie per gestirla, agendo come mediatore:</p>
				<ul>
					<li><span class="underline">Riconoscere e validare:</span> inizierebbe l'intervento riconoscendo apertamente che la
						tensione è un
						segno positivo di un lavoro ben fatto.
						Direbbe: <em>"Mi accorgo che c'è tensione tra le opzioni innovative dell'Esploratore e la necessità di cautela del
							Critico.
							È un'ottima cosa, perché significa che stiamo considerando tutte le prospettive necessarie."</em>
					</li>

					<li><span class="underline">Ascolto attento ed empatia:</span> si metterebbe dal punto di vista di ciascuno e ne
						comprenderebbe
						le emozioni:
						<ul>
							<li><strong>Verso l'Esploratore/Stratega:</strong> <em>"Capisco che l'entusiasmo per le nuove idee e
									la chiarezza del piano
									si scontrino con le obiezioni. Vi sentite bloccati proprio quando avevate trovato una direzione."</em></li>
							<li><strong>Verso il Critico:</strong> <em>"Comprendo la tua necessità di proteggere la vittima
									assicurandoti che non ci siano
									conseguenze negative inaspettate. Il tuo rigore è fondamentale per la sicurezza."</em></li>
						</ul>
					</li>
				</ul>
			</li>

			<li>
				<h4>Mediazione: riportare l'equilibrio e trovare la ragione comune</h4>
				<p>Sulla base del principio che <strong>la ragione e il torto non stanno mai da una sola parte</strong>, il Saggio
					cercherebbe il punto di incontro tra le diverse esigenze:</p>
				<ul>
					<li><span class="underline">Sfruttare la diversità di idee:</span> sottolineerebbe l'importanza di confrontarsi e
						collaborare anche con idee diverse,
						trasformando la critica in un requisito.
						<ul>
							<li><strong>Allo Stratega:</strong> <em>"Il tuo piano è solido, ma ha bisogno di integrare il rischio
									identificato dal Critico.
									Dobbiamo aggiungere una clausola di emergenza o un Piano&nbsp;B."</em></li>
							<li><strong>All'Esploratore:</strong> <em>"Le tue idee innovative sono il motore, ma necessitano di essere
									filtrate.
									Qual è l'idea 'più sicura' ma ancora 'non convenzionale' che può superare il vaglio del Critico?"</em></li>
						</ul>
					</li>

					<li><span class="underline">Separare il piano di azione (Strategia) dal fattore umano (Vittima):</span>
						ricorderebbe a tutti il focus principale — <strong>il benessere della compagna</strong>.
						Questo aiuterebbe a ridurre la carica emotiva del dibattito sulle soluzioni e a concentrarsi
						sull'<strong>obiettivo comune</strong>.
					</li>
				</ul>
			</li>

			<li>
				<h4>Decisione e Ripartenza (leadership per l'azione)</h4>
				<p>Una volta che il conflitto è stato mediato e le idee filtrate, il Saggio guida il gruppo verso una
					<strong>decisione finale</strong> che tenga conto di tutto, applicando la sua resilienza
					(<em>"Gli insuccessi non mi scoraggiano, cerco sempre il modo di ripartire"</em>):
				</p>
				<ul>
					<li><span class="underline">Sintesi e selezione:</span> combinerebbe l'idea più promettente dell'Esploratore
						con il piano più robusto dello Stratega, inserendovi le misure di mitigazione del rischio richieste dal Critico.
						Questa sintesi sarebbe la soluzione da attuare.</li>

					<li><span class="underline">Impegno all'azione:</span> prenderebbe un impegno chiaro per il primo passo, anche se
						piccolo.
						Se il piano iniziale ha mostrato fallibilità (un “insuccesso”), non si scoraggerebbe, ma proporrebbe una
						ripartenza immediata
						con un piano rivisto, sostenuto da tutto il gruppo.</li>

					<li><span class="underline">Follow-Up di gruppo:</span> si impegnerebbe a discutere periodicamente l'andamento
						dell'intervento,
						per assicurarsi che l'armonia e la collaborazione nel gruppo si mantengano e che il supporto alla compagna rimanga
						costante.</li>
				</ul>
			</li>
		</ol>
