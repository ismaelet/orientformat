			alt="Stratega"
			class="rounded-4xl w-50"
		>
		<x-heading.component-big>Lo Stratega</x-heading.component-big>

		<p class="text-block">Con il suo <strong>focus sulla chiarezza</strong>, sulla <strong>pianificazione metodica</strong>
			e sulla <strong>previsione delle conseguenze</strong>,
			trasformerebbe il problema del cyberbullismo in un <strong>progetto di intervento strutturato e controllato</strong>.
			Lo Stratega non si concentrerebbe sulla generazione di idee (come l'Esploratore), ma sulla selezione e
			<strong>l'esecuzione efficace di un piano d'azione.</strong><br><br>
			Ecco come agirebbe, in linea con le sue caratteristiche.
		</p>

		<ol>
			<li>
				<h4>Analisi e definizione chiara del problema</h4>
				<p>Per prima cosa, lo Stratega esigerebbe una spiegazione chiara e completa del fatto:</p>
				<ul>
					<li><span class="underline">Raccolta dati:</span> chiederebbe all'Esploratore e agli altri membri di fornire dati
						precisi:
						chi è coinvolto, cosa è stato detto/pubblicato, su quale piattaforma, con quale frequenza e
						l'impatto emotivo sulla vittima.</li>
					<li><span class="underline">Definizione degli obiettivi:</span> tradurrebbe la situazione in obiettivi misurabili.
						Ad esempio:
						<ul>
							<li><strong>Obiettivo 1:</strong> far cessare immediatamente le molestie.</li>
							<li><strong>Obiettivo 2:</strong> assicurare il supporto psicologico alla vittima.</li>
							<li><strong>Obiettivo 3:</strong> definire misure preventive per il futuro.</li>
						</ul>
					</li>
				</ul>
			</li>

			<li>
				<h4>Pianificazione strategica e allocazione delle risorse</h4>
				<p>Utilizzando la sua capacità di pianificare e prevedere gli esiti, lo Stratega elaborerebbe un piano
					d'azione dettagliato:</p>
				<ul>
					<li><span class="underline">Identificazione delle vie di soluzione</span>: prenderebbe in considerazione le
						diverse ipotesi (quelle generate dall'Esploratore) e le valuterebbe in base alla loro fattibilità,
						rapidità e rischio.</li>

					<li><span class="underline">Interrogarsi sulle conseguenze (analisi di impatto)</span>:
						<ul>
							<li>Conseguenza di parlare con gli insegnanti: rischio che il bullismo si sposti offline o si
								intensifichi per vendetta.</li>
							<li>Conseguenza di parlare con i genitori: rischio di reazione eccessiva che metta a disagio la
								vittima.</li>
							<li>Conseguenza di intervenire direttamente: rischio di escalation.</li>
						</ul>
						Sceglierebbe quindi il percorso con il minor rischio di danno ulteriore e la
						maggiore probabilità di successo.
					</li>

					<li><span class="underline">Organizzazione e definizione dei tempi</span>: assegnerebbe i compiti ai membri
						del gruppo (sfruttando le idee chiare su come dividere il lavoro):
						<ul>
							<li><strong>Compito 1 (immediato):</strong> documentazione delle prove (assegnato a chi è
								preciso). <em>Tempo: 4 ore.</em></li>
							<li><strong>Compito 2 (supporto):</strong> contattare lo sportello psicologico scolastico
								(assegnato al più empatico). <em>Tempo: 1 giorno.</em></li>
							<li><strong>Compito 3 (strategico):</strong> comunicazione formale e strutturata alla
								Dirigenza/famiglie (assegnato a sé stesso o a un membro con capacità comunicative
								istituzionali). <em>Tempo: 2 giorni.</em></li>
						</ul>
					</li>
				</ul>
			</li>

			<li>
				<h4>Elaborazione del progetto e controllo dell'esecuzione</h4>
				<p>Lo Stratega ama elaborare e proporre progetti. L'intervento non sarebbe una reazione casuale,
					ma un progetto strutturato e controllato:</p>
				<ul>
					<li><span class="underline">Creazione di un diagramma di flusso</span>: svilupperebbe un piano visivo (come
						un diagramma di Gantt) per monitorare lo stato di ogni attività.</li>
					<li><span class="underline">Monitoraggio e feedback</span>: verificherebbe che le attività siano eseguite con
						cura rispettando i materiali necessari (come le prove raccolte) e i tempi definiti, intervenendo se
						un'attività
						ritarda o non produce l'esito previsto.</li>
				</ul>
			</li>
		</ol>

		<p class="text-block">In sintesi, lo Stratega porta ordine, logica e un approccio step-by-step
			alla
			crisi, garantendo che l'intervento non sia emotivo, ma calcolato per massimizzare la sicurezza della vittima e
			ottenere un risultato definitivo.</p>
	</div>
</article>
