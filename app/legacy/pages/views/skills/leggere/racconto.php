	<p class="text txt-1rem txt-lh2 mar-b-3">
		In questo momento la padrona di una bettola rincorre un ragazzo che si è comprato venti cents di patate fritte e, a parere di lei, ci ha versato sopra troppo aceto dalla bottiglia presa dal tavolo.<br>
		«Cane che non sei altro, mi vuoi rovinare?»<br>
		Forse lui le tirerà in faccia le patate? No, non ce la fa a rispondere; risponde per lui soltanto l'ansimo del suo torace di bambino, un sibilare che scaturisce dalle canne gracili dei suoi polmoni [...]<br>
		La baruffa per le sei gocce d'aceto non è ancora finita; la mano della padrona si alza ancora minacciosa e dal petto del giovane esce quel lungo sibilo. Persone indifferenti passano al largo, gli ubriachi barcollano, passano correndo i ragazzi coi libri delle preghiere per arrivare in tempo alle funzioni della sera. Ma già si avvicinava il salvatore: un tipo grosso e grasso, flaccido, doveva avere perso sangue dal naso, macchie scure gli coprivano il volto intorno alla bocca e al naso. Anche lui era già passato dagli spilli di sicurezza allo spago che, evidentemente, non era bastato per le scarpe slabbrate. Si avvicinò alla padrona della bettola, le fece un bell'inchino, accennò un baciamano, tolse di tasca un biglietto da 10 scellini, glielo porse e quella lo prese spaventata; poi le disse con buona creanza:<br>
		«Posso pregarla, gentile Signora, di considerare questi dieci scellini quale adeguato compenso per sei gocce d'aceto?»<br>
		Si fece silenzio nel buio dietro a King John's Castle. Poi l'uomo insanguinato proseguì con voce più bassa:<br>
		«Posso altresì attirare la sua benigna attenzione sul fatto che è venuta l'ora delle funzioni? La prego di porgere al signor parroco i miei più rispettosi saluti.»<br>
		Si allontanò vacillando, il ragazzo impaurito scappò via e la padrona rimase sola; improvvise scesero le lacrime sul suo viso, poi tornò correndo in casa e le sue grida si sentivano ancora dopo che già la porta si era chiusa dietro di lei[...].<br>
		Dieci scellini per sei gocce d'aceto! Chi vive la poesia invece di comporla paga il diecimila per cento d'interessi.<br>
		Dov'era quell'ubriaco torvo e insanguinato cui lo spago era bastato per la giacca ma non per le scarpe? Si era forse buttato nello Shannon, nella stretta grigia e vorticosa fra i due ponti, dove i gabbiani scivolano come su una pista gratuita? Roteavano ancora nel buio, si buttavano giù verso i flutti grigi, da ponte a ponte, risalivano, per poi ripetere il gioco: insaziabili, all'infinito.<br><br>

